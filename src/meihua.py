WX_ORDER = ['金','水','木','火','土']

from .safety import DISCLAIMER


def _num_to_gua(n):
    n = n % 8
    return n if n != 0 else 8


def _num_to_yao(n):
    n = n % 6
    return n if n != 0 else 6


def _wx_sheng_wo(wx):
    i = WX_ORDER.index(wx)
    return WX_ORDER[(i - 1) % 5]


def compute_meihua(a: int, b: int, c: int, question: str = '') -> dict:
    """梅花易数起卦解卦。

    Args:
        a, b, c: 三个数字
        question: 所问之事

    Returns:
        结构化 dict，包含本卦/互卦/变卦/体用生克/综合判断
    """
    shang = _num_to_gua(a)
    xia = _num_to_gua(b)
    dong = _num_to_yao(c)

    shang_info = GUA[shang]
    xia_info = GUA[xia]

    # GUA64_INDEX key 是 (下卦, 上卦) 顺序
    bengua_idx = GUA64_INDEX[(xia, shang)]
    bengua_name = GUA64_NAMES[bengua_idx]

    # 互卦
    hugua_idx = HUGUA_MAP.get(bengua_idx, bengua_idx)
    hugua_name = GUA64_NAMES[hugua_idx]

    # 变卦
    bin_gua = bengua_idx - 1
    bit_pos = 5 - (dong - 1)
    bin_bian = bin_gua ^ (1 << bit_pos)
    biangua_idx = bin_bian + 1
    biangua_name = GUA64_NAMES[biangua_idx]

    # 体用：动爻在下卦→下卦为用，上卦为体；动爻在上卦→上卦为用，下卦为体
    if dong <= 3:
        ti_idx, yong_idx = shang, xia
    else:
        ti_idx, yong_idx = xia, shang

    ti_wx = GUA[ti_idx][2]
    yong_wx = GUA[yong_idx][2]

    # 体用生克
    if ti_wx == yong_wx:
        tiyong_result = '比和'
        tiyong_desc = '体用五行相同，吉。事情顺利，心想事成。'
    elif _wx_sheng_wo(ti_wx) == yong_wx:
        tiyong_result = '用生体（大吉）'
        tiyong_desc = f'用卦({yong_wx})生体卦({ti_wx})。凡事顺遂，有贵人相助。'
    elif WX_ORDER[(WX_ORDER.index(ti_wx)+1)%5] == yong_wx:
        tiyong_result = '体生用（耗泄）'
        tiyong_desc = f'体卦({ti_wx})生用卦({yong_wx})。需要付出很多，事情能成但很累。'
    elif WX_ORDER[(WX_ORDER.index(ti_wx)-2)%5] == yong_wx:
        tiyong_result = '用克体（凶）'
        tiyong_desc = f'用卦({yong_wx})克体卦({ti_wx})。事情不顺，阻力大，需谨慎。'
    else:
        tiyong_result = '体克用（小吉）'
        tiyong_desc = f'体卦({ti_wx})克用卦({yong_wx})。事可成但费心力，需要坚持。'

    return {
        'method': '数字起卦',
        'input': {'a': a, 'b': b, 'c': c, 'question': question},
        'shang_gua': {'name': shang_info[0], 'xiang': shang_info[1], 'wuxing': shang_info[2]},
        'xia_gua': {'name': xia_info[0], 'xiang': xia_info[1], 'wuxing': xia_info[2]},
        'dong_yao': dong,
        'bengua': {'index': bengua_idx, 'name': bengua_name, 'meaning': GUA64_MEANING[bengua_idx]},
        'hugua': {'index': hugua_idx, 'name': hugua_name, 'meaning': GUA64_MEANING[hugua_idx]},
        'biangua': {'index': biangua_idx, 'name': biangua_name, 'meaning': GUA64_MEANING[biangua_idx]},
        'tiyong': {
            'ti_gua': GUA[ti_idx][0],
            'yong_gua': GUA[yong_idx][0],
            'result': tiyong_result,
            'description': tiyong_desc,
        },
        'disclaimer': DISCLAIMER,
    }


def to_markdown(chart: dict) -> str:
    """梅花易数结果 → Markdown 报告"""
    sg = chart['shang_gua']
    xg = chart['xia_gua']
    ty = chart['tiyong']
    q = chart['input']['question']

    lines = [
        '# 梅花易数占卜',
        '',
        f'**起卦数字：** {chart["input"]["a"]} {chart["input"]["b"]} {chart["input"]["c"]}',
        f'**上卦：** {sg["name"]}（{sg["xiang"]}·属{sg["wuxing"]}）',
        f'**下卦：** {xg["name"]}（{xg["xiang"]}·属{xg["wuxing"]}）',
        f'**动爻：** 第{chart["dong_yao"]}爻动',
        '',
        '## 卦象推演',
        '',
        f'| 阶段 | 卦名 | 含义 |',
        f'|------|------|------|',
        f'| 本卦 | {chart["bengua"]["name"]} | {chart["bengua"]["meaning"]} |',
        f'| 互卦 | {chart["hugua"]["name"]} | {chart["hugua"]["meaning"]} |',
        f'| 变卦 | {chart["biangua"]["name"]} | {chart["biangua"]["meaning"]} |',
        '',
        '## 体用生克',
        '',
        f'**体卦：** {ty["ti_gua"]}（{GUA[[k for k,v in GUA.items() if v[0]==ty["ti_gua"]][0]][2]}）',
        f'**用卦：** {ty["yong_gua"]}（{GUA[[k for k,v in GUA.items() if v[0]==ty["yong_gua"]][0]][2]}）',
        f'**结果：** {ty["result"]}',
        f'**解读：** {ty["description"]}',
        '',
    ]
    if q:
        lines.append(f'## 针对「{q}」的建议')
        if '大吉' in ty['result'] or '比和' in ty['result']:
            lines.append('整体吉利，可以放心去做。')
        elif '体克用' in ty['result']:
            lines.append('事情可以做成，但需要花心思和精力。评估投入产出比。')
        elif '体生用' in ty['result']:
            lines.append('付出可能比收获多，建议评估是否值得。')
        else:
            lines.append('阻力较大，建议暂缓或换方向。')
        lines.append('')

    lines.extend([
        '---',
        f'> {chart["disclaimer"]}',
    ])
    return '\n'.join(lines)
