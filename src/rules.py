# ── 五行生克 ──
WX_ORDER = ['木', '火', '土', '金', '水']

def wx_sheng(wx: str) -> str:
    """我生者"""
    i = WX_ORDER.index(wx)
    return WX_ORDER[(i + 1) % 5]

def wx_ke(wx: str) -> str:
    """我克者"""
    i = WX_ORDER.index(wx)
    return WX_ORDER[(i + 2) % 5]

def wx_sheng_wo(wx: str) -> str:
    """生我者"""
    i = WX_ORDER.index(wx)
    return WX_ORDER[(i - 1) % 5]

def wx_ke_wo(wx: str) -> str:
    """克我者"""
    i = WX_ORDER.index(wx)
    return WX_ORDER[(i - 2) % 5]
